function report = create_pmsm_foc_data_dictionary_v21(modelNames)
%CREATE_PMSM_FOC_DATA_DICTIONARY_V21 Create the v2.1.0 data contracts.
% The dictionary is the authoritative source for control calibration,
% protection thresholds, interface bus definitions and interface metadata.
% Harness-only stimulus variables deliberately remain in the model workspace.

if nargin < 1
    modelNames = {'PMSM_FOC_DualPlant_Controller_v21', ...
        'PMSM_FOC_DualPlant_ClosedLoop_v21'};
end
if ischar(modelNames) || isstring(modelNames)
    modelNames = cellstr(modelNames);
end

versionDirectory = fileparts(mfilename('fullpath'));
dictionaryName = 'PMSM_FOC_Data.sldd';
dictionaryPath = fullfile(versionDirectory, dictionaryName);
parameterCatalog = parameterDefinitions();
interfaceCatalog = interfaceDefinitions();

if exist(dictionaryPath, 'file') == 0
    dictionary = Simulink.data.dictionary.create(dictionaryPath);
else
    dictionary = Simulink.data.dictionary.open(dictionaryPath);
end
dictionaryCleanup = onCleanup(@() closeDictionary(dictionary));
designData = getSection(dictionary, 'Design Data');

for parameterIndex = 1:numel(parameterCatalog)
    definition = parameterCatalog(parameterIndex);
    parameter = Simulink.Parameter;
    parameter.Value = castValue(definition.Default, definition.DataType);
    parameter.DataType = definition.DataType;
    parameter.Min = double(definition.Minimum);
    parameter.Max = double(definition.Maximum);
    if strcmp(definition.Unit, 'tick')
        parameter.Unit = '1';
    else
        parameter.Unit = definition.Unit;
    end
    parameter.Description = sprintf( ...
        '%s Owner=%s; Version=%s; Class=%s.', definition.Description, ...
        definition.Owner, definition.Version, definition.DataClass);
    if strcmp(definition.DataClass, 'TunableCalibration')
        parameter.CoderInfo.StorageClass = 'ExportedGlobal';
    else
        parameter.CoderInfo.StorageClass = 'Auto';
    end
    setDictionaryValue(designData, definition.Name, parameter);
end

busNames = {'ControlCommandBus', 'MeasurementBus', ...
    'ControlStatusBus', 'CalibrationBus'};
for busIndex = 1:numel(busNames)
    busName = busNames{busIndex};
    rows = interfaceCatalog(strcmp({interfaceCatalog.BusName}, busName));
    busObject = buildBusObject(busName, rows);
    setDictionaryValue(designData, busName, busObject);
end

calibrationDefaults = struct( ...
    'PhaseCurrentOffsetA', single(0), ...
    'PhaseCurrentOffsetB', single(0), ...
    'AlignmentVd', single(2), ...
    'AlignmentVq', single(0), ...
    'AlignmentDurationTicks', uint16(20), ...
    'SampleCount', uint16(100), ...
    'ParameterSetVersion', uint16(210), ...
    'ParameterSetCrc', uint32(0));
dataClassCatalog = struct( ...
    'CompileTimeConstant', 'Inlined algorithm/math invariant', ...
    'TunableCalibration', 'Exported calibration/protection parameter', ...
    'RuntimeSignal', 'Bus element exchanged at run time', ...
    'ReadOnlyDiagnostic', 'Controller status written by the controller');
setDictionaryValue(designData, 'PMSM_FOC_Parameter_Catalog', parameterCatalog);
setDictionaryValue(designData, 'PMSM_FOC_Interface_Catalog', interfaceCatalog);
setDictionaryValue(designData, 'PMSM_FOC_Data_Class_Catalog', dataClassCatalog);
setDictionaryValue(designData, 'PMSM_FOC_Calibration_Defaults', ...
    calibrationDefaults);
setDictionaryValue(designData, 'PMSM_FOC_Parameter_Set_Version', '2.1.0');
setDictionaryValue(designData, 'PMSM_FOC_Compatibility_Id', ...
    'PMSM_FOC_DUALPLANT_V21');
setDictionaryValue(designData, 'PMSM_FOC_Parameter_Set_CRC32', ...
    'TBD_BY_CALIBRATION_EXPORT_PIPELINE');
saveChanges(dictionary);

parameterNames = {parameterCatalog.Name};
for modelIndex = 1:numel(modelNames)
    modelName = modelNames{modelIndex};
    if bdIsLoaded(modelName)
        set_param(modelName, 'DataDictionary', dictionaryName);
        clearMigratedModelVariables(modelName, parameterNames);
        save_system(modelName, [], 'OverwriteIfChangedOnDisk', true);
    end
end

report.DictionaryPath = dictionaryPath;
report.ParameterCount = numel(parameterCatalog);
report.InterfaceElementCount = numel(interfaceCatalog);
report.BusCount = numel(busNames);
report.ParameterSetVersion = '2.1.0';
report.CompatibilityId = 'PMSM_FOC_DUALPLANT_V21';
report.CrcStrategy = 'TBD_BY_CALIBRATION_EXPORT_PIPELINE';
report.Pass = report.ParameterCount >= 25 && ...
    report.InterfaceElementCount >= 35 && report.BusCount == 4;

fprintf('CODEX_DATA_DICTIONARY=%s\n', dictionaryName);
fprintf('CODEX_DATA_PARAMETER_COUNT=%d\n', report.ParameterCount);
fprintf('CODEX_DATA_INTERFACE_ELEMENT_COUNT=%d\n', ...
    report.InterfaceElementCount);
fprintf('CODEX_DATA_CONTRACT_CREATION_PASS=%d\n', report.Pass);
end

