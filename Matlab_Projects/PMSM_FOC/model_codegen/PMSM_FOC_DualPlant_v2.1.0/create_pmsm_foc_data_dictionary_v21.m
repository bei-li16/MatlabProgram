function busObject = buildBusObject(busName, rows)
elements = repmat(Simulink.BusElement, numel(rows), 1);
for elementIndex = 1:numel(rows)
    row = rows(elementIndex);
    element = Simulink.BusElement;
    element.Name = row.ElementName;
    element.DataType = row.DataType;
    element.Dimensions = 1;
    element.Min = double(row.Minimum);
    element.Max = double(row.Maximum);
    if strcmp(row.Unit, 'tick')
        element.Unit = '1';
    else
        element.Unit = row.Unit;
    end
    element.Description = sprintf('Ts=%s; Class=%s; %s', ...
        row.SampleTime, row.DataClass, row.Description);
    elements(elementIndex) = element;
end
busObject = Simulink.Bus;
busObject.Elements = elements;
busObject.DataScope = 'Exported';
busObject.Description = sprintf('%s v2.1.0 interface contract', busName);
end

function value = castValue(value, dataType)
switch dataType
    case 'single'
        value = single(value);
    case 'uint8'
        value = uint8(value);
    case 'uint16'
        value = uint16(value);
    case 'uint32'
        value = uint32(value);
    case 'int8'
        value = int8(value);
    case 'boolean'
        value = logical(value);
    otherwise
        error('Unsupported data type: %s', dataType);
end
end

function setDictionaryValue(section, name, value)
try
    entry = getEntry(section, name);
    setValue(entry, value);
catch
    addEntry(section, name, value);
end
end

function clearMigratedModelVariables(modelName, parameterNames)
modelWorkspace = get_param(modelName, 'ModelWorkspace');
for parameterIndex = 1:numel(parameterNames)
    parameterName = parameterNames{parameterIndex};
    if modelWorkspace.hasVariable(parameterName)
        modelWorkspace.evalin(sprintf('clear %s', parameterName));
    end
end
end

function closeDictionary(dictionary)
try
    saveChanges(dictionary);
catch
end
try
    close(dictionary);
catch
end
end
